// Self-contained HTML report (one file, no external assets) for CI artifacts or GitHub Pages.
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const COLORS = { critical: '#b91c1c', high: '#dc2626', medium: '#d97706', low: '#2563eb', info: '#6b7280' };

/**
 * Render a report as a standalone HTML page.
 * @param {{ target: string, summaryLine?: string, findings: object[], suppressed?: object[], counts?: Record<string, number>, tool?: {name: string, version: string} }} report
 * @param {{ failOn?: string, title?: string }} [opts]
 */
export function formatHtml(report, opts = {}) {
  const title = opts.title || `${report.tool?.name || 'pkg-field-gauge'}: ${report.target}`;
  const counts = Object.entries(report.counts || {}).filter(([, n]) => n).map(([s, n]) => `<span class="pill" style="background:${COLORS[s]}">${n} ${s}</span>`).join(' ') || '<span class="pill ok">no findings</span>';
  const rows = report.findings.map((f) => `<tr><td><span class="sev" style="color:${COLORS[f.severity]}">${esc(f.severity)}</span></td><td><code>${esc(f.rule)}</code></td><td>${esc(f.message)}${f.fix ? `<div class="fix">${esc(f.fix)}</div>` : ''}</td><td><code>${esc(f.file || '')}${f.line ? `:${f.line}` : ''}</code></td></tr>`).join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(title)}</title>
<style>body{font:15px/1.5 system-ui,sans-serif;margin:2rem auto;max-width:1100px;padding:0 1rem;color:#111}h1{font-size:1.4rem}table{border-collapse:collapse;width:100%}td,th{border-bottom:1px solid #e5e7eb;padding:.5rem;text-align:left;vertical-align:top}.pill{color:#fff;border-radius:999px;padding:.1rem .6rem;font-size:.85rem}.pill.ok{background:#16a34a}.fix{color:#374151;font-size:.9rem;margin-top:.25rem}.sev{font-weight:600}footer{color:#6b7280;font-size:.85rem;margin-top:2rem}@media(prefers-color-scheme:dark){body{background:#111;color:#eee}td,th{border-color:#333}.fix{color:#aaa}}</style>
</head><body>
<h1>${esc(title)}</h1>
<p>${esc(report.summaryLine || '')}</p>
<p>${counts}</p>
${report.findings.length ? `<table><thead><tr><th>Severity</th><th>Rule</th><th>Finding</th><th>Where</th></tr></thead><tbody>
${rows}
</tbody></table>` : '<p>Everything checked out.</p>'}
${report.suppressed?.length ? `<p>${report.suppressed.length} finding(s) suppressed by the allowlist.</p>` : ''}
<footer>Generated by ${esc(report.tool?.name || 'pkg-field-gauge')} ${esc(report.tool?.version || '')}${opts.failOn ? ` · fail-on: ${esc(opts.failOn)}` : ''}</footer>
</body></html>
`;
}
